"""Regenerates the generated modules of the getricky package from openapi.json.

    uv run --no-project --python 3.12 --with datamodel-code-generator==0.83.0 \\
        python scripts/generate.py [path/to/openapi.json]

It writes two modules, both committed and never edited by hand:

- ``src/getricky/types.py``: a ``TypedDict`` for every schema, from
  datamodel-code-generator. Responses stay plain dicts, so fields and enum
  values the API adds later never break parsing.
- ``src/getricky/_operations.py``: one typed method per operation, for the
  sync and the async client, from this script.

The default spec path is this repository's ``openapi.json``.
"""

import json
import keyword
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PACKAGE = Path(__file__).resolve().parent.parent / "src" / "getricky"
DATAMODEL_CODEGEN_ARGS = [
    "--input-file-type",
    "openapi",
    "--output-model-type",
    "typing.TypedDict",
    "--target-python-version",
    "3.10",
    "--no-use-union-operator",
    "--no-use-standard-collections",
    "--enum-field-as-literal",
    "all",
    "--use-title-as-name",
    "--naming-strategy",
    "parent-prefixed",
    "--use-schema-description",
    "--use-field-description",
    "--use-double-quotes",
    "--disable-timestamp",
    "--formatters",
    "builtin",
]


def main() -> None:
    spec_path = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[3] / "openapi.json")
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    name_discriminated_variants(spec)
    write_types(spec)
    (PACKAGE / "_operations.py").write_text(operations_module(spec), encoding="utf-8")


def name_discriminated_variants(spec: dict) -> None:
    """Titles each untitled ``oneOf`` variant after its ``type`` constant, and
    the property holding it when nested, so the generated names say what each
    variant is: ``SendMessageText`` and ``TemplateMessageComponentParameterImage``
    rather than ``SendMessage1`` and ``TemplateMessageComponentParameters2``."""

    def visit(node: object, holder: str) -> None:
        if isinstance(node, dict):
            for variant in node.get("oneOf", []):
                constant = variant.get("properties", {}).get("type", {}).get("const")
                if isinstance(constant, str) and "title" not in variant:
                    variant["title"] = pascal(holder.removesuffix("s")) + pascal(constant)
            for key, value in node.items():
                if key == "properties":
                    for name, schema in value.items():
                        visit(schema, name)
                else:
                    visit(value, holder)
        elif isinstance(node, list):
            for value in node:
                visit(value, holder)

    for schema in spec["components"]["schemas"].values():
        visit(schema, "")


def write_types(spec: dict) -> None:
    executable = shutil.which("datamodel-codegen")
    if executable is None:
        sys.exit("datamodel-codegen is not installed; run this script as its docstring shows.")
    with tempfile.TemporaryDirectory() as directory:
        source = Path(directory) / "openapi.json"
        source.write_text(json.dumps(spec), encoding="utf-8")
        target = Path(directory) / "types.py"
        subprocess.run(
            [executable, "--input", str(source), "--output", str(target), *DATAMODEL_CODEGEN_ARGS],
            check=True,
            cwd=directory,
        )
        code = target.read_text(encoding="utf-8")
    # The output targets 3.10; these two names come from typing_extensions on 3.9.
    code = code.replace(", TypeAlias,", ",").replace(
        "from typing_extensions import NotRequired, TypedDict",
        "from typing_extensions import NotRequired, TypeAlias, TypedDict",
    )
    if "TypeAlias" in code.split("from typing_extensions", 1)[0]:
        sys.exit("datamodel-codegen changed its imports; update write_types().")
    (PACKAGE / "types.py").write_text(code, encoding="utf-8")


def operations_module(spec: dict) -> str:
    operations = [
        operation_spec(spec, path, method, operation)
        for path, item in spec["paths"].items()
        for method, operation in item.items()
    ]
    models = sorted({model for operation in operations for model in operation["models"]})
    literal = any("Literal[" in parameter["annotation"] for operation in operations for parameter in operation["query"])
    lines = [
        "# This file is auto-generated by scripts/generate.py from openapi.json.",
        "",
        "from typing import Any, " + ("Literal, " if literal else "") + "Optional, cast",
        "",
        "from ._page import Page, Resource",
        "from .types import (",
        *[f"    {model}," for model in models],
        ")",
        "",
        "",
    ]
    for asynchronous in (False, True):
        lines += [
            f"class {'Async' if asynchronous else 'Sync'}Operations:",
            f'    """Every operation of the Ricky API{", awaitable" if asynchronous else ""}."""',
            "",
            "    def _request(self, method: str, path: str, **options: Any) -> Any:",
            "        raise NotImplementedError",
            "",
        ]
        for operation in operations:
            lines += method_lines(operation, asynchronous)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def operation_spec(spec: dict, path: str, method: str, operation: dict) -> dict:
    parameters = [resolve(spec, parameter) for parameter in operation.get("parameters", [])]
    success = next(code for code in operation["responses"] if code.startswith("2"))
    data = operation["responses"][success]["content"]["application/json"]["schema"]["properties"]["data"]
    is_list = data.get("type") == "array"
    item = ref_name(data["items"] if is_list else data)
    body = operation.get("requestBody")
    body_model = ref_name(body["content"]["application/json"]["schema"]) if body else None
    query = [
        {
            "name": p["name"],
            # A Python keyword (`from`) takes a trailing underscore, as PEP 8 advises.
            "argument": p["name"] + "_" if keyword.iskeyword(p["name"]) else p["name"],
            "annotation": query_annotation(p["schema"]),
            "description": p.get("description", ""),
        }
        for p in parameters
        if p["in"] == "query"
    ]
    return {
        "body": body_model,
        "body_required": bool(body and body.get("required")),
        "description": operation.get("description", ""),
        "idempotent": any(p["in"] == "header" and p["name"].lower() == "idempotency-key" for p in parameters),
        "method": method.upper(),
        "models": [m for m in (item, body_model) if m],
        "name": snake(operation["operationId"]),
        "path": path,
        "path_parameters": [p["name"] for p in parameters if p["in"] == "path"],
        "query": query,
        "returns": f"Page[{item}]" if is_list else f"Resource[{item}]",
        "summary": operation.get("summary", ""),
    }


def method_lines(operation: dict, asynchronous: bool) -> list:
    arguments = ["self"] + [f"{name}: str" for name in operation["path_parameters"]]
    if operation["body"]:
        arguments.append(
            f"body: {operation['body']}"
            if operation["body_required"]
            else f"body: Optional[{operation['body']}] = None"
        )
    keywords = [f"{p['argument']}: Optional[{p['annotation']}] = None" for p in operation["query"]]
    if operation["idempotent"]:
        keywords.append("idempotency_key: Optional[str] = None")
    if keywords:
        arguments += ["*", *keywords]
    call = [f'"{operation["method"]}"', f'"{operation["path"]}"']
    if operation["path_parameters"]:
        call.append("path_parameters={" + ", ".join(f'"{n}": {n}' for n in operation["path_parameters"]) + "}")
    if operation["query"]:
        call.append("query={" + ", ".join(f'"{p["name"]}": {p["argument"]}' for p in operation["query"]) + "}")
    if operation["body"]:
        call.append("body=body")
    if operation["idempotent"]:
        call += ["idempotent=True", "idempotency_key=idempotency_key"]
    prefix = "async def" if asynchronous else "def"
    lines = [f"    {prefix} {operation['name']}("]
    lines += [f"        {argument}," for argument in arguments]
    lines.append(f"    ) -> {operation['returns']}:")
    lines += docstring(operation)
    lines.append(f"        return cast({operation['returns']}, {'await ' if asynchronous else ''}self._request(")
    lines += [f"            {argument}," for argument in call]
    lines += ["        ))", ""]
    return lines


def docstring(operation: dict) -> list:
    text = operation["summary"] + ".\n\n" + operation["description"].strip()
    parameter_lines = [f"{p['argument']}: {p['description']}" for p in operation["query"] if p["description"]]
    if operation["idempotent"]:
        parameter_lines.append(
            "idempotency_key: Retrying with the same key replays the first response. "
            "The client sends a random one when you pass none."
        )
    if parameter_lines:
        text += "\n\nArgs:\n" + "\n".join("    " + line for line in parameter_lines)
    lines = [("        " + line).rstrip() for line in text.replace('"""', "'''").split("\n")]
    lines[0] = '        """' + lines[0].lstrip()
    return [*lines, '        """']


def query_annotation(schema: dict) -> str:
    if "enum" in schema:
        return "Literal[" + ", ".join(json.dumps(value) for value in schema["enum"]) + "]"
    return {"integer": "int", "number": "float", "boolean": "bool"}.get(schema.get("type"), "str")


def resolve(spec: dict, value: dict) -> dict:
    if "$ref" not in value:
        return value
    node = spec
    for part in value["$ref"].lstrip("#/").split("/"):
        node = node[part]
    return node


def ref_name(schema: dict) -> str:
    if "$ref" not in schema:
        raise SystemExit(f"Expected a $ref schema, got {json.dumps(schema)[:120]}")
    return schema["$ref"].rsplit("/", 1)[1]


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def pascal(value: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[^0-9A-Za-z]+", value) if part)


if __name__ == "__main__":
    main()
