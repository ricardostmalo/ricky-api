// Regenerates src/generated/ from the OpenAPI description.
//
//   npm run generate                      # reads ../../openapi.json (this repository's copy)
//   npm run generate -- path/to/openapi.json
//
// The output is committed and never edited by hand. The same spec and the
// pinned @hey-api/openapi-ts version always produce the same files.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { createClient } from '@hey-api/openapi-ts';

const spec = resolve(process.argv[2] ?? '../../openapi.json');
const output = 'src/generated';

await createClient({
  input: spec,
  logs: { level: 'silent' },
  output: { importFileExtension: '.js', path: output },
  plugins: [
    // Throwing is the default; the Ricky class turns every failure into a RickyError.
    { name: '@hey-api/client-fetch', throwOnError: true },
    '@hey-api/typescript',
    {
      name: '@hey-api/sdk',
      operations: { containerName: 'RickyApi', methods: 'instance', strategy: 'single' },
      paramsStructure: 'grouped',
      responseStyle: 'data',
    },
  ],
});

// Writes that accept an Idempotency-Key: the client adds one when the caller
// did not, and retries only requests that carry one (or are reads).
const document = JSON.parse(readFileSync(spec, 'utf8'));
const idempotent = [];
for (const [path, item] of Object.entries(document.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    const parameters = operation.parameters ?? [];
    const takesKey = parameters.some((parameter) => {
      const resolved = parameter.$ref
        ? document.components.parameters[parameter.$ref.split('/').pop()]
        : parameter;
      return resolved.in === 'header' && resolved.name.toLowerCase() === 'idempotency-key';
    });
    if (takesKey) idempotent.push(`${method.toUpperCase()} ${path}`);
  }
}
idempotent.sort();
writeFileSync(
  resolve(output, 'idempotency.gen.ts'),
  [
    '// This file is auto-generated by scripts/generate.mjs',
    '',
    '/** `METHOD /path/{template}` of every write that accepts an `Idempotency-Key` header. */',
    'export const idempotentOperations: ReadonlySet<string> = new Set([',
    ...idempotent.map((operation) => `    '${operation}',`),
    ']);',
    '',
  ].join('\n'),
);
